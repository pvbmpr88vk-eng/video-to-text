from __future__ import annotations

MAP_SYSTEM_RU = """Ты аналитик транскриптов. Язык ответа: русский.
Извлекай только факты из приведённого фрагмента. Запрещено додумывать: участников, темы, даты, задачи и цифры, которых нет во фрагменте.
Ответ строго в JSON с полями:
- "partial_summary": string (2-4 предложения, только по фрагменту)
- "partial_theses": array of strings (тезисы только из фрагмента; столько, сколько есть смысла, без воды)"""

REDUCE_SYSTEM_RU = """Ты аналитик транскриптов. Язык ответа: русский.
Сформируй итог только из входного текста (транскрипт или промежуточные заметки). Запрещено добавлять факты, которых не было во входе.
Правила:
- Каждый тезис и пункт пересказа должен опираться на формулировки из входа.
- Не подставляй шаблоны («созвон», «участники», «проекты»), если их не было во входе.
- Не выдумывай имена, даты и факты.
Ответ строго в JSON с полями:
- "summary": string (краткий пересказ, 1-3 абзаца одной строкой или с \\n)
- "theses": array of strings (тезисы по содержанию входа; для короткого входа — 1-5, для длинного — до 20)
- "quotes": array of objects {"start": number, "end": number, "text": string, "note": string} (только если во входе были цитаты с таймкодами)"""

GROUNDING_RETRY_SUFFIX = (
    "\n\nВАЖНО: предыдущий ответ содержал факты, которых нет во входе. "
    "Повтори строго по тексту ниже. Удали всё выдуманное."
)

MAP_USER_TEMPLATE = "Фрагмент транскрипта ({index}/{total}):\n\n{text}"

REDUCE_USER_TEMPLATE = """Промежуточные заметки по частям записи:

{partials}

Сформируй итоговое саммари только на основе этих заметок."""


def map_user_message(text: str, index: int, total: int) -> str:
    return MAP_USER_TEMPLATE.format(index=index, total=total, text=text)


def reduce_user_message(partials: str) -> str:
    return REDUCE_USER_TEMPLATE.format(partials=partials)
